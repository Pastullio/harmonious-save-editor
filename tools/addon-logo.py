"""Puts the LiveLink logo (src/assets/livelink/tile0-2.png, three square pieces of the banner, 256-colour PNGs) into the
Blender add-on as base64, between the LOGO markers, so the add-on stays one .py file.
Usage: python3 tools/addon-logo.py"""
import base64, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
addon = os.path.join(root, "desktop", "addon", "harmonious_live_link.py")
tiles = [base64.b64encode(open(os.path.join(root, "src", "assets", "livelink", "tile%d.png" % i), "rb").read()).decode() for i in range(3)]
block = "# ---- LOGO (generated by tools/addon-logo.py from src/assets/livelink) ----\nLOGO_TILES = (\n" + "".join(
    '    "%s",\n' % t for t in tiles) + ")\n# ---- /LOGO ----"
s = open(addon, encoding="utf-8").read()
s2 = re.sub(r"# ---- LOGO .*?# ---- /LOGO ----", lambda _: block, s, flags=re.S)
assert s2 != s or block in s, "no LOGO markers in the add-on"
open(addon, "w", encoding="utf-8", newline="\n").write(s2)
print("logo:", sum(len(t) for t in tiles), "base64 characters")
